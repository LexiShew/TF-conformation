#!/usr/bin/env python3
"""
gen_pilot_configs.py — generate config/pilots/<tf>.sh from config/pilots.tsv.

    python scripts/pipeline/gen_pilot_configs.py              # regenerate all
    python scripts/pipeline/gen_pilot_configs.py --check      # fail if any stale (CI)
    python scripts/pipeline/gen_pilot_configs.py --only ndt80 # one pilot
    python scripts/pipeline/gen_pilot_configs.py --diff       # show what would change

WHY
---
Pilot configs used to be hand-written, which is how the TBP pilot ran for months
against NDT80's motif (docs/tbp_label_error_downstream.md). The fix is not more
review — it is removing the opportunity:

  * PWM_LABEL is never typed. It is looked up from config/deeppbs_pdb_pwms.csv
    keyed on pdb_id. If the master table has no row for the structure, or lists
    several candidate motifs with no unambiguous pick, generation FAILS rather
    than guessing. A label that does not belong to the structure cannot be
    written down.
  * The 5 parameters that were byte-identical in all 12 pilots (FOLD,
    RAMP_STAGES, STEPS_PER_STAGE, RECOVERY_RAMP_STAGES, RECOVERY_STEPS_PER_STAGE)
    are no longer repeated per file; they live in lib/common.sh defaults.
  * The 11 *_dnarelax.sh files were pure boilerplate — every one carried the same
    two-line delta. They are replaced by ARM=dnarelax, handled in common.sh.

Generated files carry a DO-NOT-EDIT header and a content hash, so --check can
tell "someone edited the generated file" from "the registry moved on".
"""
import argparse
import csv
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
REGISTRY = os.path.join(ROOT, "config", "pilots.tsv")
PWM_CSV = os.path.join(ROOT, "config", "deeppbs_pdb_pwms.csv")
ID_TXT = os.path.join(ROOT, "data", "folds", "id.txt")
OUT_DIR = os.path.join(ROOT, "config", "pilots")

MARK = "# @generated by scripts/pipeline/gen_pilot_configs.py — DO NOT EDIT"

# HOCOMOCO labels are preferred over JASPAR when a structure has both, purely
# for consistency with the existing folds (which key on whichever the benchmark
# used). When the master table offers a genuine choice we refuse to pick.
def choose_label(pdb, row, registry_hint=None):
    """Return (label, why) or raise ValueError. Never guesses silently."""
    allp = [p for p in (row.get("all_pwms") or "").split(";") if p]
    if not allp:
        raise ValueError(
            f"{pdb}: deeppbs_pdb_pwms.csv has a row but no PWMs listed. "
            f"Cannot derive PWM_LABEL.")
    if registry_hint:
        if registry_hint in allp:
            return registry_hint, f"registry pin, present in master table"
        raise ValueError(
            f"{pdb}: registry pins pwm_label={registry_hint!r} but the master "
            f"table lists only {allp}. Refusing — this is the TBP-class error.")
    if len(allp) == 1:
        return allp[0], "sole PWM for this structure in the master table"
    # Prefer the id_txt_pwm column when the benchmark itself names one.
    idp = (row.get("id_txt_pwm") or "").strip()
    if idp and idp in allp:
        return idp, "named by id_txt_pwm in the master table"
    hoco = [p for p in allp if ".H11MO." in p]
    jasp = [p for p in allp if p.endswith(".jaspar")]
    if len(hoco) == 1:
        return hoco[0], f"sole HOCOMOCO label (JASPAR alternatives: {jasp})"
    if len(jasp) == 1 and not hoco:
        return jasp[0], "sole JASPAR label"
    raise ValueError(
        f"{pdb}: master table lists {len(allp)} PWMs with no unambiguous pick "
        f"({allp}). Add a pwm_label column value to config/pilots.tsv to pin it "
        f"explicitly — generation will verify the pin against this list.")


TEMPLATE = """#!/bin/bash
{mark}
# Source registry : config/pilots.tsv
# Generator       : scripts/pipeline/gen_pilot_configs.py
# Registry hash   : {rhash}
#
# Edit config/pilots.tsv and re-run the generator. Hand edits here are lost and
# will make `gen_pilot_configs.py --check` fail.
#
# Pilot: {tf_name} / {pdb_id}
#
# {notes}

export TF_NAME="{tf_name}"
export PDB_ID="{pdb_id}"

# PWM_LABEL is DERIVED, not typed: looked up in config/deeppbs_pdb_pwms.csv
# keyed on pdb_id={pdb_id}.
#   reason: {label_why}
# This is the guard against the TBP-class error, where a hand-typed label
# belonged to a different protein than the structure.
export PWM_LABEL="{pwm_label}"

# Eval subset. TEST_FILTER_NAME says plainly whether this is a true on-target
# subset or a family-transfer one.
export TEST_PWM_FILTER="{test_pwm_filter}"
export TEST_FILTER_NAME="{test_filter_name}"
# on-target guard: "no" means no on-target statistic may be reported for this
# pilot. scripts/pipeline/validate_pilot.py enforces it.
export ON_TARGET_USABLE="{on_target_usable}"{on_target_n_line}

# Stage 1 ensemble selector: the source-chain FILENAME letter
# ({pdb_id}_chain{binding_chain}_protein.pdb -> "{binding_chain}"). Distinct from
# PROTEIN_CHAIN, which is the 0-based mdtraj chainid into the .cif. Stage 2's
# sequence-match guard asserts the two indexings point at the same protein.
export BINDING_CHAIN="{binding_chain}"

# Stage 2 chain layout for {pdb_id}.cif
# (verify with: python stage2_redock/stage2_redock.py --ref {ref_cif} --inspect-only)
export PROTEIN_CHAIN={protein_chain}
export DNA_CHAINS="{dna_chains}"

# Frames in the BioEmu xtc (drives the Stage 3 array size)
export N_FRAMES={n_frames}

# Stage 3 ramp params, FOLD and FNAT_FLOOR come from lib/common.sh defaults —
# they were byte-identical across all pilots, so they are no longer repeated
# here. Override in this registry row only if a pilot genuinely needs to differ.
#
# The DNA-relaxation arm is NOT a separate config file any more. Use:
#     ARM=dnarelax ./scripts/pipeline/run_pilot.sh {tf_name}
"""


def registry_hash():
    with open(REGISTRY, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:12]


def read_registry():
    rows = []
    with open(REGISTRY) as fh:
        lines = [l for l in fh if not l.startswith("#") and l.strip()]
    for row in csv.DictReader(lines, delimiter="\t"):
        rows.append({k: (v or "").strip() for k, v in row.items() if k})
    return rows


def read_pwm_table():
    t = {}
    with open(PWM_CSV) as fh:
        for row in csv.DictReader(fh):
            t[row["pdb_id"].strip().lower()] = row
    return t


def read_ids():
    if not os.path.exists(ID_TXT):
        return []
    return [l.strip() for l in open(ID_TXT) if l.strip()]


def render(row, pwm_table, ids, rhash):
    tf, pdb = row["tf_name"], row["pdb_id"].lower()

    prow = pwm_table.get(pdb)
    if prow is None:
        raise ValueError(
            f"{tf}: pdb_id={pdb} is not in config/deeppbs_pdb_pwms.csv, so "
            f"PWM_LABEL cannot be derived. Add the structure to the master "
            f"table first — do not hand-write the label.")
    label, why = choose_label(pdb, prow, row.get("pwm_label") or None)

    # Leakage guard at generation time, not just validation time.
    leaked = [e for e in ids if e.lower().startswith(pdb + "_")]
    if leaked:
        raise ValueError(
            f"{tf}: source PDB {pdb} appears in data/folds/id.txt "
            f"({', '.join(leaked[:3])}). Using it as an augmentation source "
            f"leaks held-out test data into training. Pick a different "
            f"structure from the same family.")

    # Declared on-target count must match reality.
    filt = row["test_pwm_filter"]
    try:
        n_match = len([e for e in ids if re.search(filt, e)])
    except re.error as e:
        raise ValueError(f"{tf}: test_pwm_filter is not a valid regex: {e}")
    declared = row.get("on_target_n") or ""
    if declared and declared.isdigit() and int(declared) != n_match:
        raise ValueError(
            f"{tf}: registry says on_target_n={declared} but the filter "
            f"{filt!r} matches {n_match} id.txt entries. Fix one or the other.")
    usable = (row.get("on_target_usable") or "yes").lower()
    if usable not in ("yes", "no"):
        raise ValueError(f"{tf}: on_target_usable must be yes|no, got {usable!r}")
    if usable == "yes" and n_match == 0:
        raise ValueError(
            f"{tf}: on_target_usable=yes but the filter matches 0 entries. "
            f"Stage 7 would silently skip the subset. Set it to 'no' or fix "
            f"the filter.")

    n_line = (f"\nexport ON_TARGET_N_EXPECTED={declared}" if declared else "")
    notes = row.get("notes") or "(no notes)"
    # wrap notes at ~76 chars as shell comments
    words, lines, cur = notes.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > 74:
            lines.append(cur); cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        lines.append(cur)
    notes_block = "\n# ".join(lines)

    return TEMPLATE.format(
        mark=MARK, rhash=rhash, tf_name=tf, pdb_id=pdb, notes=notes_block,
        pwm_label=label, label_why=why,
        test_pwm_filter=filt, test_filter_name=row["test_filter_name"],
        on_target_usable=usable, on_target_n_line=n_line,
        binding_chain=row["binding_chain"], protein_chain=row["protein_chain"],
        dna_chains=row["dna_chains"], n_frames=row["n_frames"],
        ref_cif=f"structures/source_chains/{pdb}_chains/{pdb}.cif",
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any generated config is missing or stale")
    ap.add_argument("--diff", action="store_true", help="show changes, write nothing")
    ap.add_argument("--only", help="only this pilot")
    a = ap.parse_args()

    rhash = registry_hash()
    rows = read_registry()
    pwm_table = read_pwm_table()
    ids = read_ids()

    if a.only:
        rows = [r for r in rows if r["tf_name"] == a.only]
        if not rows:
            print(f"ERROR: {a.only} not in {REGISTRY}", file=sys.stderr)
            return 1

    failures, stale, written = [], [], []
    for row in rows:
        tf = row["tf_name"]
        try:
            text = render(row, pwm_table, ids, rhash)
        except ValueError as e:
            failures.append(str(e))
            continue
        path = os.path.join(OUT_DIR, f"{tf}.sh")
        old = open(path).read() if os.path.exists(path) else None

        if old is not None and MARK not in old:
            stale.append(f"{tf}: {path} exists but is NOT generator-owned "
                         f"(no @generated marker). Migrate it into "
                         f"config/pilots.tsv, then delete it.")
            continue
        if old == text:
            continue
        if a.check:
            stale.append(f"{tf}: {os.path.relpath(path, ROOT)} is stale")
        elif a.diff:
            import difflib
            print("\n".join(difflib.unified_diff(
                (old or "").splitlines(), text.splitlines(),
                fromfile=f"{tf}.sh (current)", tofile=f"{tf}.sh (generated)",
                lineterm="")))
        else:
            os.makedirs(OUT_DIR, exist_ok=True)
            with open(path, "w") as fh:
                fh.write(text)
            os.chmod(path, 0o755)
            written.append(tf)

    for f in failures:
        print(f"ERROR  {f}", file=sys.stderr)
    for s in stale:
        print(f"STALE  {s}", file=sys.stderr)

    if failures:
        print(f"\n{len(failures)} pilot(s) FAILED generation. Nothing written for them.",
              file=sys.stderr)
        return 1
    if a.check:
        if stale:
            print(f"\n{len(stale)} config(s) out of date. Run "
                  f"gen_pilot_configs.py to regenerate.", file=sys.stderr)
            return 1
        print(f"All {len(rows)} pilot config(s) up to date with pilots.tsv.")
        return 0
    if written:
        print(f"Wrote {len(written)} config(s): {', '.join(written)}")
    elif not a.diff:
        print(f"All {len(rows)} config(s) already current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
